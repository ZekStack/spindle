import type { LocalGitInspection } from './git-inspection'
import type { GitSafetyCode } from './git-safety'
import type { TagMutationRequest } from './tags'
import type { SafeReleaseMutation } from './releases'
import type { StoredDispatchRequest } from './release-strategies'
import type { StoredWorkflowControl } from './workflow-controls'

/** Safe, serializable operation data. No token, request header or raw command output. */
export type JobKind = 'repository-inspection' | 'local-git-inspection' |
  'local-git-clone' | 'local-git-fetch' | 'local-git-pull' | 'local-git-tag' | 'github-release' | 'github-workflow-dispatch' | 'github-workflow-control'
export type JobPhase = 'queued' | 'running' | 'completed' | 'partial' | 'failed' | 'cancelled' | 'interrupted'
export type JobErrorCode = GitSafetyCode | 'forbidden' | 'not-found' | 'rate-limit' |
  'timeout' | 'interrupted' | 'git-unavailable' | 'git-failed' | 'output-limit' |
  'tag-stale' | 'tag-exists' | 'tag-missing' | 'tag-partial' | 'release-stale' | 'release-uncertain' | 'dispatch-uncertain' | 'workflow-stale' | 'workflow-uncertain' | 'unknown'

export interface JobRecord {
  id: string
  kind: JobKind
  repository: string
  /** Canonical folder selected using Electron's native picker; local jobs only. */
  location?: string
  /** Only linked inspections can request remote tag metadata. */
  linkedRepository?: string
  /** Snapshot contains bounded counts and sanitized refs, never filenames or raw URLs. */
  inspection?: LocalGitInspection
  /** Only the confirmed ref preconditions, never an annotation message, are persisted. */
  tagOperation?: Omit<TagMutationRequest, 'message'>
  /** Durable partial-success flag for combined remote-first deletion. */
  tagRemoteDeleted?: boolean
  /** Captured at tag-push queue time: never infer workflow from later settings. */
  releaseWorkflowId?: number
  /** Safe operation metadata; release notes and native asset paths are transient. */
  releaseOperation?: SafeReleaseMutation
  /** Workflows, refs and tag SHA are safe; dispatch inputs must remain transient. */
  dispatchOperation?: StoredDispatchRequest
  /** Auditable workflow metadata only. Dispatch input values never persist. */
  workflowControl?: StoredWorkflowControl
  action: 'inspect' | 'clone' | 'fetch' | 'pull' | 'tag' | 'release' | 'dispatch' | 'workflow-control'
  requestedAt: string
  startedAt: string | null
  finishedAt: string | null
  phase: JobPhase
  progress: number
  output: string[]
  errorCode: JobErrorCode | null
  /** True when the same operation is likely to work without changing access or configuration. */
  retryable?: boolean
}

export const activeJob = (phase: JobPhase): boolean =>
  phase === 'queued' || phase === 'running'

/** Only UUIDs generated by main may be used to query/cancel an operation. */
export function validateJobId(id: unknown): string {
  if (typeof id !== 'string' ||
      !/^[a-f0-9]{8}-[a-f0-9]{4}-[1-8][a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/i.test(id)) {
    throw new Error('Invalid job ID')
  }
  return id
}
